export function renderOutputDiff(existing, expected, options = {}) {
  const existingLines = splitDiffLines(existing);
  const expectedLines = splitDiffLines(expected);
  const context = options.context ?? 3;
  const maxChangedLines = options.maxChangedLines ?? 80;

  let prefix = 0;
  while (prefix < existingLines.length
    && prefix < expectedLines.length
    && existingLines[prefix] === expectedLines[prefix]) {
    prefix += 1;
  }

  let suffix = 0;
  while (suffix < existingLines.length - prefix
    && suffix < expectedLines.length - prefix
    && existingLines[existingLines.length - 1 - suffix] === expectedLines[expectedLines.length - 1 - suffix]) {
    suffix += 1;
  }

  const oldStart = prefix;
  const oldEnd = existingLines.length - suffix;
  const newEnd = expectedLines.length - suffix;
  const contextStart = Math.max(0, oldStart - context);
  const contextEnd = Math.min(expectedLines.length, newEnd + context);
  const removed = existingLines.slice(oldStart, oldEnd);
  const added = expectedLines.slice(prefix, newEnd);
  const lines = [
    `--- ${options.fromLabel ?? "current"}`,
    `+++ ${options.toLabel ?? "generated"}`,
    `@@ line ${contextStart + 1} @@`
  ];

  for (const line of expectedLines.slice(contextStart, oldStart)) {
    lines.push(`  ${line}`);
  }

  appendChangedDiffLines(lines, "-", removed, maxChangedLines);
  appendChangedDiffLines(lines, "+", added, maxChangedLines);

  if (removed.length > maxChangedLines || added.length > maxChangedLines) {
    lines.push(`  ... diff truncated after ${maxChangedLines} removed and ${maxChangedLines} added lines`);
  }

  for (const line of expectedLines.slice(newEnd, contextEnd)) {
    lines.push(`  ${line}`);
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

function appendList(lines, label, items) {
  if (!items || items.length === 0) {
    lines.push(`- ${label}: none detected`);
    return;
  }

  lines.push(`- ${label}: ${items.map((item) => `\`${item}\``).join(", ")}`);
}

function appendSignals(lines, label, items) {
  if (!items || items.length === 0) {
    lines.push(`- ${label}: none detected`);
    return;
  }

  const formatted = items.map((item) => `\`${item.name}\` (${item.evidence})`);
  lines.push(`- ${label}: ${formatted.join(", ")}`);
}

function formatSignalNames(items) {
  if (!items || items.length === 0) {
    return "none detected";
  }

  return formatLimitedList(items.map((item) => item.name), 6);
}

