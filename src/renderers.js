function renderPowerShellCompletion() {
  const options = [
    "--root",
    "--out",
    "--target",
    "--no-write",
    "--print",
    "--dry-run",
    "--json",
    "--check",
    "--diff",
    "--doctor",
    "--health",
    "--github-actions",
    "--ci-workflow",
    "--install-github-actions",
    "--init-github-actions",
    "--setup",
    "--bootstrap",
    "--summary",
    "--stats",
    "--targets",
    "--list-targets",
    "--explain",
    "--why",
    "--strict",
    "--fail-on-warnings",
    "--force",
    "--config",
    "--no-config",
    "--config-example",
    "--print-config",
    "--init-config",
    "--install-config",
    "--show-config",
    "--effective-config",
    "--completion",
    "--ignore",
    "--max-files",
    "--quiet",
    "--version",
    "--help"
  ];
  const targets = [...TARGET_OUTPUTS.keys(), ALL_TARGETS];
  const shells = Array.from(COMPLETION_SHELLS);
  const psArray = (values) => values.map((value) => `'${value.replaceAll("'", "''")}'`).join(", ");

  return `Register-ArgumentCompleter -Native -CommandName agent-rake -ScriptBlock {
  param($wordToComplete, $commandAst, $cursorPosition)

  $options = @(${psArray(options)})
  $targets = @(${psArray(targets)})
  $shells = @(${psArray(shells)})
  $tokens = @($commandAst.CommandElements | ForEach-Object { $_.Extent.Text })
  $previous = if ($tokens.Count -ge 2) { $tokens[$tokens.Count - 2] } else { "" }

  if ($previous -eq "--target") {
    $targets |
      Where-Object { $_ -like "$wordToComplete*" } |
      ForEach-Object {
        [System.Management.Automation.CompletionResult]::new($_, $_, [System.Management.Automation.CompletionResultType]::ParameterValue, $_)
      }
    return
  }

  if ($previous -eq "--completion") {
    $shells |
      Where-Object { $_ -like "$wordToComplete*" } |
      ForEach-Object {
        [System.Management.Automation.CompletionResult]::new($_, $_, [System.Management.Automation.CompletionResultType]::ParameterValue, $_)
      }
    return
  }

  if (@("--root", "--out", "--config", "--ignore") -contains $previous) {
    $pathPattern = if ([string]::IsNullOrWhiteSpace($wordToComplete)) { "*" } else { "$wordToComplete*" }

    Get-ChildItem -Path $pathPattern -Force -ErrorAction SilentlyContinue |
      ForEach-Object {
        $completionText = $_.FullName
        if ($_.PSIsContainer) {
          $completionText = $completionText + [System.IO.Path]::DirectorySeparatorChar
        }
        [System.Management.Automation.CompletionResult]::new($completionText, $_.Name, [System.Management.Automation.CompletionResultType]::ProviderItem, $completionText)
      }
    return
  }

  $options |
    Where-Object { $_ -like "$wordToComplete*" } |
    ForEach-Object {
      [System.Management.Automation.CompletionResult]::new($_, $_, [System.Management.Automation.CompletionResultType]::ParameterName, $_)
    }
}
`;
}

function formatCommandNames(commands) {
  if (!commands || commands.length === 0) {
    return "none confidently inferred";
  }

  return formatLimitedList(commands.map((command) => command.command), 6);
}

function formatFirstReadCounts(scan) {
  return [
    `${scan.entrypoints.length} entrypoints`,
    `${scan.routeFiles.length} routes/APIs`,
    `${scan.testFiles.length} tests`,
    `${scan.envFiles.length} env templates`,
    `${scan.dataFiles.length} data/schema`,
    `${scan.ciFiles.length} CI`,
    `${scan.configFiles.length} config`
  ].join(", ");
}

function formatHotspotSummary(files) {
  if (!files || files.length === 0) {
    return "none detected";
  }

  return `${files.length} (${formatLimitedList(files, 3)})`;
}

function appendDoctorCheck(lines, label, ok, detail) {
  lines.push(`- [${ok ? "ok" : "warn"}] ${label}: ${detail}`);
}

function formatJavaScriptLockDoctorDetail(lockFiles, hasPackageJson, hasJsLock) {
  if (!hasPackageJson) {
    return "no package.json manifest detected; check skipped";
  }

  if (hasJsLock) {
    return formatLimitedList(lockFiles.filter((file) => JAVASCRIPT_LOCK_FILES.has(file)), 4);
  }

  return "package.json exists without package-lock.json, pnpm-lock.yaml, yarn.lock, bun.lock, or bun.lockb";
}

function formatGeneratedOutputDoctorDetail(outputs) {
  const staleOutputs = outputs.filter((output) => !output.ok);

  if (staleOutputs.length === 0) {
    return outputs.length === 1
      ? `\`${outputs[0].path}\` is current`
      : `${outputs.length} generated outputs are current`;
  }

  return staleOutputs
    .map((output) => `\`${output.path}\` is ${output.reason}`)
    .join(", ");
}

function formatGeneratedOutputFixTarget(outputs) {
  if (outputs.length === 1) {
    return `\`${outputs[0].path}\``;
  }

  return `${outputs.length} generated outputs`;
}

function doctorSuggestionForWarning(warning) {
  if (warning.startsWith("File scan was truncated")) {
    return "Increase `--max-files`, run from a smaller package root, or add irrelevant large directories to the scanner ignore list.";
  }

  if (warning.startsWith("No source files")) {
    return "Run from the repository root, or add source files before relying on a generated brief.";
  }

  if (warning.startsWith("No standard project manifest")) {
    return "Add or verify a standard manifest such as `package.json`, `pyproject.toml`, `go.mod`, `Cargo.toml`, `composer.json`, `pubspec.yaml`, or `Gemfile`.";
  }

  if (warning.startsWith("package.json exists without")) {
    return "Commit the JavaScript lockfile for the package manager in use, such as `package-lock.json`, `pnpm-lock.yaml`, `yarn.lock`, `bun.lock`, or `bun.lockb`.";
  }

  if (warning.startsWith("No existing AGENTS.md")) {
    return "Create repo instructions with `agent-rake --target agents`, use another single target, or run `agent-rake --target all`.";
  }

  if (warning.startsWith("Secret-looking `.env` files")) {
    return "Keep secret-bearing `.env` files out of generated context and add a safe `.env.example`, `.env.sample`, or `.env.template`.";
  }

  return warning;
}

function formatLimitedList(items, limit) {
  const visible = items.slice(0, limit);
  const suffix = items.length > limit ? `, +${items.length - limit} more` : "";
  return `${visible.map((item) => `\`${item}\``).join(", ")}${suffix}`;
}

function appendExplanations(lines, explanations = []) {
  lines.push("## Why These Signals");
  lines.push("");

  if (explanations.length === 0) {
    lines.push("- No classified signals were available to explain.");
    lines.push("");
    return;
  }

  for (const explanation of explanations) {
    lines.push(`- ${explanation.category} \`${explanation.item}\`: ${explanation.reason}`);
  }

  lines.push("");
}

function formatLanguageSummary(languages) {
  if (!languages || languages.length === 0) {
    return "not detected";
  }

  return languages
    .slice(0, 5)
    .map((item) => `${item.language} (${item.files})`)
    .join(", ");
}

function appendChangedDiffLines(lines, marker, changedLines, maxLines) {
  for (const line of changedLines.slice(0, maxLines)) {
    lines.push(`${marker} ${line}`);
  }
}

function hasJavaScriptLockFile(lockFiles) {
  return lockFiles.some((file) => JAVASCRIPT_LOCK_FILES.has(file));
}

function normalizeLineEndings(value) {
  return value.replace(/\r\n/g, "\n");
}

function splitDiffLines(value) {
  const normalized = normalizeLineEndings(value);
  if (normalized.endsWith("\n")) {
    return normalized.slice(0, -1).split("\n");
  }

  return normalized.split("\n");
}
