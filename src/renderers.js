export function renderMarkdown(scan) {
  const lines = [];

  lines.push("# Agent Brief");
  lines.push("");
  lines.push(`Generated by agent-rake for \`${scan.root}\`.`);
  lines.push("");
  lines.push("## Repo Snapshot");
  lines.push("");
  lines.push(`- Root: \`${scan.displayRoot ?? scan.root}\``);
  lines.push(`- Files scanned: ${scan.filesScanned}${scan.truncated ? " (truncated by --max-files)" : ""}`);
  lines.push(`- Primary languages: ${formatLanguageSummary(scan.languages)}`);
  lines.push(`- Package manager: ${scan.packageManager || "not detected"}`);
  if (scan.customIgnores?.length > 0) {
    lines.push(`- Custom ignores: ${scan.customIgnores.map((pattern) => `\`${pattern}\``).join(", ")}`);
  }
  lines.push("");

  lines.push("## Stack Signals");
  lines.push("");
  appendList(lines, "Manifests", scan.manifests);
  appendList(lines, "Lockfiles", scan.lockFiles);
  appendSignals(lines, "Framework signals", scan.frameworks);
  appendSignals(lines, "Workspace signals", scan.workspaces);
  appendList(lines, "Docs", scan.docs);
  appendList(lines, "Existing agent instructions", scan.instructionFiles);
  lines.push("");

  lines.push("## Commands Agents Should Prefer");
  lines.push("");
  if (scan.commands.length === 0) {
    lines.push("- No runnable command was confidently inferred. Read the manifest files before inventing one.");
  } else {
    for (const command of scan.commands) {
      lines.push(`- \`${command.command}\` - ${command.reason}`);
    }
  }
  lines.push("");

  lines.push("## Files To Read First");
  lines.push("");
  appendList(lines, "Entrypoints", scan.entrypoints);
  appendList(lines, "Routes and APIs", scan.routeFiles);
  appendList(lines, "Tests", scan.testFiles);
  appendList(lines, "Environment files", scan.envFiles);
  appendList(lines, "Data and schema files", scan.dataFiles);
  appendList(lines, "CI", scan.ciFiles);
  appendList(lines, "Config", scan.configFiles);
  lines.push("");

  lines.push("## Risk Hotspots");
  lines.push("");
  if (scan.hotspotFiles.length === 0) {
    lines.push("- No obvious auth, payment, migration, webhook, database, queue, or security hotspot files were detected.");
  } else {
    for (const file of scan.hotspotFiles) {
      lines.push(`- \`${file}\``);
    }
  }
  lines.push("");

  lines.push("## Agent Rules For This Repo");
  lines.push("");
  lines.push("- Start with the files listed above before making broad edits.");
  lines.push("- Preserve generated, dependency, cache, build, and vendor directories.");
  lines.push("- Treat `.env` and secret-bearing files as sensitive; prefer examples and docs.");
  lines.push("- Prefer the detected package manager and commands over global fallbacks.");
  lines.push("- Run the smallest relevant test command before claiming a code change is done.");
  lines.push("");

  if (scan.warnings.length > 0) {
    lines.push("## Warnings");
    lines.push("");
    for (const warning of scan.warnings) {
      lines.push(`- ${warning}`);
    }
    lines.push("");
  }

  if (scan.explain) {
    appendExplanations(lines, scan.explanations);
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

export function renderSummary(scan) {
  const warnings = scan.warnings ?? [];
  const lines = [];

  lines.push(`agent-rake summary for \`${scan.displayRoot ?? scan.root}\``);
  lines.push("");
  lines.push(`Status: ${warnings.length > 0 || scan.truncated ? "review warnings" : "no scan warnings"}`);
  lines.push(`Files scanned: ${scan.filesScanned}${scan.truncated ? " (truncated by --max-files)" : ""}`);
  lines.push(`Primary languages: ${formatLanguageSummary(scan.languages)}`);
  lines.push(`Package manager: ${scan.packageManager || "not detected"}`);
  if (scan.customIgnores?.length > 0) {
    lines.push(`Custom ignores: ${formatLimitedList(scan.customIgnores, 6)}`);
  }
  lines.push(`Framework signals: ${formatSignalNames(scan.frameworks)}`);
  lines.push(`Workspace signals: ${formatSignalNames(scan.workspaces)}`);
  lines.push(`Commands: ${formatCommandNames(scan.commands)}`);
  lines.push(`First-read files: ${formatFirstReadCounts(scan)}`);
  lines.push(`Risk hotspots: ${formatHotspotSummary(scan.hotspotFiles)}`);
  lines.push(`Warnings: ${warnings.length === 0 ? "none" : warnings.length}`);

  if (warnings.length > 0) {
    lines.push("");
    lines.push("Warning details:");
    for (const warning of warnings) {
      lines.push(`- ${warning}`);
    }
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

export function renderDoctor(scan, generatedOutput = null) {
  const warnings = scan.warnings ?? [];
  const generatedOutputs = generatedOutput?.outputs ?? [];
  const generatedOutputFailures = generatedOutputs.filter((output) => !output.ok);
  const hasPackageJson = scan.manifests.includes("package.json");
  const hasJsLock = hasJavaScriptLockFile(scan.lockFiles);
  const lines = [];

  lines.push(`agent-rake doctor for \`${scan.displayRoot ?? scan.root}\``);
  lines.push("");
  lines.push(`Status: ${warnings.length === 0 ? "no scan warnings" : `${warnings.length} warning${warnings.length === 1 ? "" : "s"} need review`}`);
  lines.push("");
  lines.push("Checks:");
  appendDoctorCheck(lines, "Scan breadth", !scan.truncated, scan.truncated
    ? "scan hit --max-files before seeing the full repo"
    : `scanned ${scan.filesScanned} files`);
  appendDoctorCheck(lines, "Source files", scan.filesScanned > 0, scan.filesScanned > 0
    ? `${scan.filesScanned} files available for metadata scan`
    : "no source files were found");
  appendDoctorCheck(lines, "Manifest", scan.manifests.length > 0, scan.manifests.length > 0
    ? formatLimitedList(scan.manifests, 4)
    : "no standard project manifest was detected");
  appendDoctorCheck(lines, "JavaScript lockfile", !hasPackageJson || hasJsLock, formatJavaScriptLockDoctorDetail(scan.lockFiles, hasPackageJson, hasJsLock));
  appendDoctorCheck(lines, "Agent instructions", scan.instructionFiles.length > 0, scan.instructionFiles.length > 0
    ? formatLimitedList(scan.instructionFiles, 4)
    : "no AGENTS.md, CLAUDE.md, CODEX.md, Cursor rule, or Copilot instruction file was detected");
  appendDoctorCheck(lines, "Environment hygiene", !warnings.some((warning) => warning.startsWith("Secret-looking `.env` files")), warnings.some((warning) => warning.startsWith("Secret-looking `.env` files"))
    ? "secret-looking .env files were found and intentionally not listed"
    : "no secret-looking .env files detected");
  if (generatedOutputs.length > 0) {
    appendDoctorCheck(lines, "Generated output", generatedOutputs.every((output) => output.ok), formatGeneratedOutputDoctorDetail(generatedOutputs));
  }

  if (warnings.length > 0 || generatedOutputFailures.length > 0) {
    lines.push("");
    lines.push("Fix suggestions:");
    for (const warning of warnings) {
      lines.push(`- ${doctorSuggestionForWarning(warning)}`);
    }
    if (generatedOutputFailures.length > 0) {
      lines.push(`- Run \`${generatedOutput?.updateCommand ?? "agent-rake"}\` to refresh ${formatGeneratedOutputFixTarget(generatedOutputFailures)}.`);
    }
  }

  lines.push("");
  lines.push("Useful next commands:");
  lines.push("- `agent-rake --summary` for a compact snapshot.");
  lines.push("- `agent-rake --diff` before committing generated output.");
  lines.push("- `agent-rake --github-actions` to print a CI workflow.");

  return `${lines.join("\n").trimEnd()}\n`;
}

export function renderTargets() {
  const lines = [];
  const longestName = Math.max(...[...TARGET_OUTPUTS.keys(), ALL_TARGETS].map((name) => name.length));

  lines.push("agent-rake targets");
  lines.push("");
  lines.push("Use with: agent-rake --target <name>");
  lines.push("");

  for (const [name, output] of TARGET_OUTPUTS) {
    lines.push(`${name.padEnd(longestName)}  ${output}`);
  }

  lines.push(`${ALL_TARGETS.padEnd(longestName)}  all known target outputs`);

  return `${lines.join("\n").trimEnd()}\n`;
}

export function renderCompletion(shell) {
  if (!COMPLETION_SHELLS.has(shell)) {
    throw new Error(`--completion must be one of: ${Array.from(COMPLETION_SHELLS).join(", ")}`);
  }

  if (shell === "bash") {
    return renderBashCompletion();
  }

  if (shell === "zsh") {
    return renderZshCompletion();
  }

  if (shell === "fish") {
    return renderFishCompletion();
  }

  return renderPowerShellCompletion();
}

